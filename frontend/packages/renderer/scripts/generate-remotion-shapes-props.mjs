import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageRoot = path.resolve(__dirname, "..");
const outFile = path.resolve(
  packageRoot,
  "src/generated/remotion-shapes-props.ts",
);
const tmpFile = path.resolve(packageRoot, ".tmp-remotion-shapes-props.ts");

function getComponentNames(exportsMap) {
  return Object.entries(exportsMap)
    .filter(([name, value]) => /^[A-Z]/.test(name) && typeof value === "function")
    .map(([name]) => name)
    .sort();
}

function buildVirtualSource(componentNames) {
  const aliases = componentNames
    .map(
      (name) =>
        `type __${name}Props = PropsOf<typeof RemotionShapes.${name}>;\ntype __${name}SpecificProps = Parameters<typeof RemotionShapes.make${name}>[0];`,
    )
    .join("\n");

  return `import type React from "react";
import * as RemotionShapes from "@remotion/shapes";

type PropsOf<T> = T extends React.ComponentType<infer P> ? P : never;

${aliases}
`;
}

function getPropsForAlias(checker, sourceFile, aliasName) {
  const symbol = checker
    .getSymbolsInScope(sourceFile, ts.SymbolFlags.TypeAlias)
    .find((item) => item.getName() === aliasName);

  if (!symbol) {
    return [];
  }

  const type = checker.getDeclaredTypeOfSymbol(symbol);
  if (type.flags & ts.TypeFlags.Never) {
    return [];
  }

  return checker
    .getPropertiesOfType(type)
    .map((prop) => prop.getName())
    .sort((a, b) => a.localeCompare(b));
}

function buildOutput(propsMap) {
  const componentProps = {};
  const specificProps = {};

  for (const [name, value] of Object.entries(propsMap)) {
    componentProps[name] = value.componentProps;
    specificProps[name] = value.specificProps;
  }

  return `/* eslint-disable */\n/*\n * AUTO-GENERATED FILE.\n * Generated by: scripts/generate-remotion-shapes-props.mjs\n */\n\nexport const REMOTION_SHAPES_PROP_MAP: Record<string, readonly string[]> = ${JSON.stringify(
    componentProps,
    null,
    2,
  )} as const;\n\nexport const REMOTION_SHAPES_SPECIFIC_PROP_MAP: Record<string, readonly string[]> = ${JSON.stringify(
    specificProps,
    null,
    2,
  )} as const;\n`;
}

async function main() {
  const remotionShapes = await import("@remotion/layout-utils");
  const componentNames = getComponentNames(remotionShapes);

  if (componentNames.length === 0) {
    throw new Error("No Remotion shape components were found");
  }

  fs.writeFileSync(tmpFile, buildVirtualSource(componentNames), "utf8");

  const program = ts.createProgram([tmpFile], {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    jsx: ts.JsxEmit.ReactJSX,
    skipLibCheck: true,
    strict: false,
  });

  const checker = program.getTypeChecker();
  const sourceFile = program.getSourceFile(tmpFile);

  if (!sourceFile) {
    throw new Error(`Could not read temporary source file: ${tmpFile}`);
  }

  const propsMap = {};

  for (const name of componentNames) {
    const componentAlias = `__${name}Props`;
    const specificAlias = `__${name}SpecificProps`;
    propsMap[name] = {
      componentProps: getPropsForAlias(checker, sourceFile, componentAlias),
      specificProps: getPropsForAlias(checker, sourceFile, specificAlias),
    };
  }

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, buildOutput(propsMap), "utf8");
  fs.rmSync(tmpFile, { force: true });

  console.log(
    `Generated ${path.relative(packageRoot, outFile)} for ${componentNames.length} shape components`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
